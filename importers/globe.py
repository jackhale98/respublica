def unt_words(page: int, year: int = 1866) -> list[Word]:
    """UNT's OCR words with their boxes, in UNT's order (IIIF annotations)."""
    data = json.loads(gzip.decompress(raw_path(words_id(page, year)).read_bytes()))
    out = []
    for r in data.get("resources", []):
        x, y, w, h = (int(v) for v in r["on"].split("#xywh=")[1].split(","))
        out.append(Word(r["resource"].get("chars", ""), x, y, x + w, y + h, 0))
    return out


def unt_lines(page: int, year: int = 1866) -> list[str]:
    """UNT's OCR of the page as lines of text (the page's "OCR" view)."""
    t = gzip.decompress(raw_path(text_id(page, year)).read_bytes()).decode("utf-8")
    m = re.search(r'(?s)<div id="ocr-text"[^>]*>(.*?)</div>', t)
    _expect(m is not None, f"p. {page}: no OCR text in {text_id(page, year)}")
    return [html.unescape(re.sub(r"<[^>]+>", "", l)).strip() for l in re.split(r"<br\s*/?>", m.group(1))]


def unt_page(page: int, year: int = 1866) -> Page:
    """The page from UNT's two views of one OCR: the words' boxes, in the
    annotations' order, which reads line by line (a line ends where the next
    word goes back to the left or down a line); each word's spelling, with
    punctuation, from the text, matched in order by letters and figures.
    Punctuation standing alone in the text ("—") goes with the word before
    it; a box the text has no word for keeps the annotation's spelling."""
    refined = SESSIONS[year].refined
    # (Refined: a "word" one or two dots wide is a column rule read as a
    # letter, "j The SPEAKER.")
    boxes = [w for w in unt_words(page, year) if key(w.text) and not (refined and w.x1 - w.x0 <= 2)]
    tokens: list[str] = []
    for line in unt_lines(page, year):
        started = False
        for t in line.split():
            started = started or bool(key(t))
            if refined and not started:
                continue  # (refined) specks at the start of a line are not the last line's ("world.-")
            if key(t) or not tokens:
                tokens.append(t)
            else:
                tokens[-1] += t
    keyed = [t for t in tokens if key(t)]
    sm = SequenceMatcher(None, [key(w.text) for w in boxes], [key(t) for t in keyed], autojunk=False)
    spelling: dict[int, str] = {}
    for op, a1, a2, b1, b2 in sm.get_opcodes():
        if op == "equal" or (op == "replace" and a2 - a1 == b2 - b1):
            for k in range(a2 - a1):
                spelling[a1 + k] = keyed[b1 + k]
    lines: list[Line] = []
    for a, w in enumerate(boxes):
        word = Word(spelling.get(a, w.text), w.x0, w.y0, w.x1, w.y1, 0)
        if lines:
            last = lines[-1].words[-1]
            h = max(last.height, word.height, 1)
            if word.x0 >= last.x1 - 0.5 * h and abs((word.y0 + word.y1) - (last.y0 + last.y1)) / 2 < 0.6 * h:
                lines[-1].words.append(word)
                continue
        lines.append(Line([word]))
    p = Page(page, max((w.x1 for w in boxes), default=0), max((w.y1 for w in boxes), default=0))
    if SESSIONS[year].refined:
        lines = [l for l in lines if not (SIGNATURE.match(l.text) and l.words[0].y0 > 0.9 * p.height)]
    p.paras = [Para([l], page) for l in lines]
    return p


# The signature of a number of the Globe, at the foot of its first page:
# "40th Cong. 3d Sess.—No. 8.", "38th Cong. 2d Sess.—No. 13." as OCR reads it.
SIGNATURE = re.compile(r"(?i)^\W*\d{2}\w{1,3}\.?\s*Co\S{1,4}\s+\S{2,4}\s*S\S{2,5}\W*No\b")


def paragraphs(col: Page, refined: bool = False) -> list[Para]:
    """A column's lines (one to a paragraph, as UNT gives them) made into
    paragraphs: a paragraph ends at a line that stops short of the right
    margin when the next is indented, and a centred line (a heading) stands
    alone. Refined (`Session.refined`): a line in small capitals set in a
    little from both margins is a heading too, and a heading may run over two lines, the first in
    small capitals and not ending a sentence ("THE DEATH OF SLAVERY IS THE
    LIFE OF THE / NATION.", the title of a speech in 1864)."""
    lines = sorted((l for para in col.paras for l in para.lines), key=lambda l: l.words[0].y0)
    if not lines:
        return []
    # The margin where each line is: scans are often skewed, so a column's
    # flush-left lines drift (from x 12 at the top to -11 at the foot); the
    # lower quartile of the starts of the fifteen lines around each line.
    starts = [l.x0 for l in lines]
    margins = [sorted(starts[max(0, k - 7):k + 8])[len(starts[max(0, k - 7):k + 8]) // 4] for k in range(len(lines))]
    # Straighten the column: each line moved by its margin, so that later
    # steps (`ocr.blocks`, joining paragraphs across columns) see one margin.
    lines = [Line([Word(w.text, w.x0 - m, w.y0, w.x1 - m, w.y1, w.conf) for w in l.words])
             for l, m in zip(lines, margins)]
    margins = [0] * len(lines)
    right = sorted(max(w.x1 for w in l.words) for l in lines)[int(len(lines) * 0.9)]
    lo_off, hi_off = max(4, col.width * 0.012), col.width * 0.12

    def indented(k: int) -> bool:
        return lo_off < lines[k].x0 - margins[k] < hi_off

    tops = [l.words[0].y0 for l in lines]
    gaps = [b - a for a, b in zip(tops, tops[1:])]
    leading = sorted(gaps)[len(gaps) // 2] if gaps else 0

    def heading(k: int) -> bool:
        """Centred, or standing apart with space above and below (a heading
        in small capitals may fill the column)."""
        l = lines[k]
        # (A speck after the full stop is not print: "ABOLITION OF SLAVERY. Vf".)
        stops = (".", ",") if refined else "."  # (refined: "SUFFRAGE, 4")
        ws = l.words[:-1] if len(l.words) > 1 and len(l.words[-1].text) <= 2 and l.words[-2].text.endswith(stops) \
            else l.words
        if l.x0 > margins[k] + col.width * 0.08 and max(w.x1 for w in ws) < right - col.width * 0.08:
            return True
        if (refined and l.x0 > margins[k] + col.width * 0.03 and max(w.x1 for w in ws) < right - col.width * 0.03
                and one_case(" ".join(w.text for w in ws)) and len(ws) >= 2):
            return True  # (refined) a long heading in small capitals, nearly filling the column
        above = gaps[k - 1] if k > 0 else float("inf")
        below = gaps[k] if k < len(gaps) else float("inf")
        # (Not the last line of a paragraph, which goes on from a line that
        # does not end a sentence: "… where there / is no peace.")
        ends_sentence = k == 0 or re.search(r"[.:?!\"')\]]$", lines[k - 1].text.rstrip())
        t = " ".join(w.text for w in ws).rstrip()
        return (bool(leading) and above > 1.2 * leading and below > 1.2 * leading and t.endswith(stops)
                and one_case(t) and bool(ends_sentence))

    def first_of_pair(k: int) -> bool:
        """The first line of a heading of two lines."""
        t = lines[k].text.rstrip()
        return (refined and k + 1 < len(lines) and not heading(k) and heading(k + 1) and one_case(t)
                and not re.search(r"[.:?!\"')\]]$", t) and len(t.split()) >= 2
                and (k == 0 or bool(re.search(r"[.:?!\"')\]]$", lines[k - 1].text.rstrip()))))

    out: list[list[Line]] = [[lines[0]]]
    for k in range(1, len(lines)):
        prev, line = lines[k - 1], lines[k]
        short = max(w.x1 for w in prev.words) < right - col.width * 0.05
        # A speaker's words always begin a paragraph, indented, even after a
        # line that runs nearly to the margin.
        speaker = SPEAKER.match(line.text) and indented(k)
        if first_of_pair(k - 1):
            pass  # the second line of a heading of two
        elif (short and indented(k)) or speaker or heading(k) or heading(k - 1) or first_of_pair(k):
            out.append([])
        out[-1].append(line)
    index = {id(l): k for k, l in enumerate(lines)}
    # A paragraph whose first line opens with a speaker, indented, begins a
    # paragraph even at the head of a column (`ocr.blocks` would join it to
    # the column before when the indent is slight).
    return [Para(ls, col.leaf, heading=(len(ls) == 1 and heading(index[id(ls[0])]))
                 or (len(ls) == 2 and first_of_pair(index[id(ls[0])])),
                 starts=bool(SPEAKER.match(ls[0].text)) and indented(index[id(ls[0])])) for ls in out]


# The running head: the page number, the title, and the date.
HEAD = re.compile(r"(?i)congressional|globe|\b\d{3,4}\b")
# The masthead of a number of the Globe (1864-65), in place of the running
# head on its first page: "THE OFFICIAL PROCEEDINGS OF CONGRESS, PUBLISHED BY
# JOHN C. RIVES, WASHINGTON, D. C." over "Thirty-Eighth Congress, 1st
# Session. … TUESDAY, MARCH 29, 1864. … New Series.....No. 83."
MASTHEAD = re.compile(r"OFFICIAL\s+P|PUBLISHED\s+BY")
# A running head OCR garbled ("H34& MB (DONGrRESSIONATi GHOBEi March 80!"):
# a short row across the top of the page with figures, a month or a piece
# of the title (`refined` reading only).
GARBLED_HEAD = re.compile(r"(?i)\d{2}|congr|gl\w{2}e|january|february|march|april|may|june|july|december")
MASTHEAD_END = re.compile(r"(?i)session|series")


def head_of(page: Page, refined: bool = False) -> tuple[str, set[int]]:
    """The running head's text and its lines (empty if the page has none),
    with the masthead's rows on the first page of a number (1864-65; above
    them, "THE CONGRESSIONAL GLOBE." in 1865)."""
    lines = [l for para in page.paras for l in para.lines]
    all_rows = [r for r in rows(lines) if not is_speck(r)]
    first = all_rows[0] if all_rows else None

    def text(r: list[Line]) -> str:
        return " ".join(l.text for l in r)

    # (Refined: the masthead may be the third row, under the title read
    # "THE CONGRESS" and a speck.)
    m = next((k for k, r in enumerate(all_rows[:3 if refined else 2]) if MASTHEAD.search(text(r))
              and r[0].words[0].y0 < 0.12 * page.height), None)
    if not (first and first[0].words[0].y0 < 0.08 * page.height
            and (HEAD.search(text(first)) or MASTHEAD.search(text(first)) or (refined and m is not None)
                 or (refined and GARBLED_HEAD.search(text(first)) and len(text(first).split()) <= 10
                     and max(w.x1 for l in first for w in l.words) - min(l.x0 for l in first) > 0.6 * page.width))):
        return "", set()
    top = max(l.words[0].y0 for l in first)
    if m is not None:
        # Down to the row naming the session and the number.
        k = next((k for k in range(m + 1, min(m + 3, len(all_rows))) if MASTHEAD_END.search(text(all_rows[k]))), m)
        top = max(l.words[0].y0 for l in all_rows[k])
    head_rows = [r for r in rows(lines) if r[0].words[0].y0 <= top]
    return " | ".join(text(r) for r in head_rows), {id(l) for r in head_rows for l in r}


def column_pages(page: Page, number: int, reference: bool = False, refined: bool = False) -> list[Page] | None:
    """The page's columns, numbered by its printed page, or None for a page
    not set in three columns (`refined`: see `Session.refined`)."""
    _, head_ids = head_of(page, refined)
    columns = split_columns(page, head_ids, COLUMNS, reference)
    if columns is None:
        return None
    for col in columns:
        col.paras = paragraphs(col, refined) if not reference else col.paras
        mark_notes(col)
        col.folio = col.number = str(number)
    return columns


def page_number(head: str, year: int = 1866) -> int | None:
    """The page number in a running head (not the year in its date)."""
    m = re.search(r"\b(\d{4})\b", head.replace(str(year), " "))
    return int(m.group(1)) if m else None


def settle_pages(read: dict[int, int | None]) -> dict[int, int]:
    """Printed page numbers by scan page, checked against the pages around
    them: a number read in the head counts when its offset from the scan's
    page count is the one most pages within ten read; any other page takes
    its number from that offset (as `ocr.settle_folios` does)."""
    from collections import Counter
    offsets = {leaf: n - leaf for leaf, n in read.items() if n}
    out = {}
    for leaf in read:
        near = Counter(off for l, off in offsets.items() if abs(l - leaf) <= 10)
        off, count = near.most_common(1)[0] if near else (None, 0)
        if count >= 2:
            out[leaf] = leaf + off
    return out


