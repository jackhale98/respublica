CHUNK = 200


def prepare(its: list[Item], session: Session) -> dict[int, list[dict]]:
    """Each block's words aligned with the other copies' readings."""
    refs = references(session)
    hints: dict[str, int] = {}
    readings: dict[int, list[dict]] = {}
    for it in its:
        stream = [*([it.heading] if it.heading else []), *(b for b in it.body if b.kind != "note")]
        # An item is aligned as one run of words (1866), or (refined) in runs
        # of paragraphs of at least CHUNK words: an item's opening words are
        # often a formula ("The SPEAKER. The next business in order is …")
        # repeated day after day, which would place a whole long item at
        # another day's.
        chunks: list[list[Block]] = [[]]
        for b in stream:
            if session.refined and sum(len(TOKEN.findall(x.text)) for x in chunks[-1]) >= CHUNK:
                chunks.append([])
            chunks[-1].append(b)
        for chunk in chunks:
            tokens = [TOKEN.findall(b.text) for b in chunk]
            aligned = align([t for ts in tokens for t in ts], refs, hints)
            at = 0
            for b, ts in zip(chunk, tokens):
                readings[id(b)] = aligned[at:at + len(ts)]
                at += len(ts)
        for b in it.body:
            if b.kind == "note":
                readings[id(b)] = align(TOKEN.findall(b.text), refs, dict(hints))
    return readings


def build(house: str, year: int, its: list[Item], readings: dict[int, list[dict]], known: set[str]) -> dict:
    session = SESSIONS[year]
    work_id, prefix, title, short, scope = WORKS[(house, year)]
    divisions, segments = [], []
    seen: dict[str, int] = {}
    for it in its:
        day = f"{it.date.strftime('%b')}{it.date.day}"
        seen[day] = seen.get(day, 0) + 1
        suffix = "" if seen[day] == 1 else "bcdefgh"[seen[day] - 2]
        base = f"{prefix}.{day}{suffix}"
        label = f"{it.date.strftime('%B')} {it.date.day}, {it.date.year}" + (f" ({seen[day]})" if suffix else "")
        div = {"date": it.date.isoformat(), "label": label, "level": 1, "ref": base}
        if it.heading is not None:
            head, spans = text_of_readings(readings[id(it.heading)], known)
            div["title"] = head
            if spans:
                div["uncertain"] = {"title": spans}
        divisions.append(div)
        body = [b for b in it.body if b.kind != "note"]
        notes = [b for b in it.body if b.kind == "note"]
        for kind, bs, ref_of, label_of in (
                (None, body, lambda n: f"{base}.{n}", lambda n: f"{house}, {label}, ¶ {n}"),
                ("footnote", notes, lambda n: f"{base}.fn{n}", lambda n: f"{house}, {label}, note {n}")):
            for n, b in enumerate(bs, 1):
                text, spans, fixed = corrections.apply(ref_of(n), *text_of_readings(readings[id(b)], known))
                first_page = int(b.folios[0])
                seg = {"label": label_of(n), "pages": b.folios, "ref": ref_of(n),
                       "scan": {"item": unt_record(first_page, year), "leaves": [unt_leaf(first_page, year)],
                                "site": "unt"},
                       "text": text}
                if kind:
                    seg["kind"] = kind
                if spans:
                    seg["uncertain"] = spans
                if fixed:
                    seg["corrected"] = fixed
                segments.append(seg)
    pages = sorted({int(f) for s in segments for f in s["pages"]})
    copies = copies_used(session)
    checked = ("checked word by word against scans of two other copies" if len({c.name for c in copies}) > 1
               else "checked word by word against a scan of another copy")
    return {
        "date": f"{its[0].date.isoformat()}/{its[-1].date.isoformat()}",
        "divisions": divisions,
        "edition": {"name": session.edition,
                    "notes": f"{session.edition}: the items of the {house}'s proceedings {scope}, "
                             f"pp. {pages[0]}–{pages[-1]}. Read from the UNT Digital Library's OCR of its copy and "
                             f"{checked}; words they could not settle are marked as uncertain. See docs/editions.md."},
        "id": work_id,
        "ref_prefix": prefix,
        "segments": segments,
        "short": short,
        "source_ids": sorted({sid for p in pages for sid in (words_id(p, year), text_id(p, year))})
                      + list(dict.fromkeys(c.source_id for c in copies)),
        "title": title,
    }


def run(out_dir: Path = TEXTS_DIR, years: tuple[int, ...] = tuple(SESSIONS)) -> list[Path]:
    paths = []
    for year in years:
        session = SESSIONS[year]
        its = all_items(year)
        readings = prepare(its, session)
        known = Vocabulary(clean_vocabulary())
        for r in readings.values():
            known.attest(attested(r))
        for (house, y), work in WORKS.items():
            if y != year:
                continue
            mine = [it for it in its if it.house == house]
            path = out_dir / f"{work[0]}.json"
            write_json(path, build(house, year, mine, readings, known))
            paths.append(path)
    return paths


