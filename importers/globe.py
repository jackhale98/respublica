@dataclass(frozen=True)
class Session:
    """A session of Congress as the Globe prints it: its UNT records (by the
    pages each holds), the other copies read against UNT's, and how the
    items on the amendment are headed and name the joint resolution."""
    year: int  # the year of the debates: in source ids and refs
    congress: str  # "39th Congress, 1st session"
    edition: str
    parts: tuple[tuple[str, int, int], ...]  # (UNT record, first page, last page)
    copies: tuple[Copy, ...]
    headings: tuple[str, ...]  # the subject headings, in letters ("reconstruction")
    subject: re.Pattern  # the joint resolution, as an item's first paragraphs name it
    # How the page is read, refined for 1864-65 and 1869 (decision 57): a
    # subject heading OCR ends with a comma, a speck or nothing is still a
    # heading (`is_subject_heading`); a heading may run over two lines
    # (`paragraphs`); the number's signature at the foot of its first page
    # ("40th Cong. 3d Sess.—No. 8.") is left out (`unt_page`). Not in 1866,
    # whose refs were published before: there a heading read "RKCON STKUC
    # nOX— AGAIN" (June 13) stays a paragraph of the item before it, and the
    # signatures stay in the text (docs/errata.md, 27 and 28).
    refined: bool = True
    # The other copies' OCR text reads a vote's tally apart from the last
    # name ("and Wright— 37."), where UNT's reads it as one word ("Wright—37.");
    # joined (`join_tallies`), the copies agree and the count is kept. Only
    # in 1866 so far (decision 58); the other sessions' texts would change.
    tallies: bool = False


