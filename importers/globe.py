MONTHS = ("January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
          "November", "December")


# A vote's tally after the last name, read apart from it: "and Wright— 37.",
# "Yates — 7.", "Williams.— 14.".
TALLY = re.compile(r"\b([A-Z][A-Za-z]*\.?)[ \t]*([—-])[ \t]+(\d{1,3}[.,])(?=\s)")


def join_tallies(text: str) -> str:
    """A tally joined to the name before it, as UNT's OCR reads it ("Wright—37.")."""
    return TALLY.sub(r"\1\2\3", text)


def copy_text(copy: Copy, session: Session) -> str:
    """A copy's OCR text from the first of the session's days it holds on:
    the part of it the imported items can be in. The day is found by its
    dateline ("Tuesday, May 8, 1866"), or failing that by its date; if
    neither is read, by the next day's."""
    t = read_raw_text(copy.source_id)
    days = [d for _, d, first, _ in days_of(session.year) if copy.first <= first <= copy.last]
    for date in days:
        month, weekday = MONTHS[date.month - 1], date.strftime("%A")
        for pattern in (rf"{weekday},\s+{month}\s+{date.day},\s+{date.year}", rf"{month}\s+{date.day},\s*{date.year}"):
            at = re.search(pattern, t)
            if at:
                return t[at.start():]
    raise ImportError_(f"{copy.source_id}: none of the days {days} found")


def microfilm_text(copy: Copy, first: int, last: int, year: int = 1866) -> str:
    """A microfilm's OCR with page layout, pages first to last, column by
    column without running heads (its OCR runs lines across the columns)."""
    pages = [p for p in parse_djvu_xml(raw_path(copy.source_id)) if sum(len(x.words) for x in p.paras) >= 100]
    numbers = settle_pages({p.leaf: page_number(head_of(p)[0], year) for p in pages})
    out = []
    for p in pages:
        n = numbers.get(p.leaf)
        if n is None or not first <= n <= last:
            continue
        for col in column_pages(p, n, reference=True) or []:
            out.extend(l.text for para in col.paras for l in para.lines)
    return "\n".join(out)


def references(session: Session) -> list[Reference]:
    """The other copies' readings, one stream per name (a copy in several
    volumes is read as one, in page order)."""
    days = days_of(session.year)
    texts: dict[str, list[str]] = {}
    for copy in session.copies:
        if not any(copy.first <= first <= copy.last for _, _, first, _ in days):
            continue
        if copy.kind == "xml":
            text = microfilm_text(copy, copy.first, max(last for _, _, _, last in days), session.year)
        else:
            text = copy_text(copy, session)
        if session.tallies:
            text = join_tallies(text)
        texts.setdefault(copy.name, []).append(text)
    return [Reference(name, "\n".join(parts)) for name, parts in texts.items()]


def copies_used(session: Session) -> list[Copy]:
    days = days_of(session.year)
    return [c for c in session.copies if any(c.first <= first <= c.last for _, _, first, _ in days)]


