def unt_leaves(record: str) -> dict[int, int]:
    """The leaf of each printed page in a UNT record (canvases count from 1),
    from its IIIF manifest's labels. In 1864-65 the first page of each
    number of the Globe (one in sixteen) is unlabelled ("No Page #"): it
    takes the leaf between its neighbours', if they agree."""
    from tools.common import fetch_bytes
    m = json.loads(fetch_bytes(f"https://digital.library.unt.edu/ark:/67531/{record}/manifest/"))
    canvases = m["sequences"][0]["canvases"]
    labels = [c["label"] for c in canvases]
    leaves = {int(l): n for n, l in enumerate(labels, 1) if l.isdigit()}
    for page in range(min(leaves), max(leaves) + 1):
        if page in leaves:
            continue
        guesses = {leaves[page - 1] + 1} if page - 1 in leaves else set()
        guesses |= {leaves[page + 1] - 1} if page + 1 in leaves else set()
        if len(guesses) == 1:
            leaf = guesses.pop()
            if 0 < leaf <= len(labels) and labels[leaf - 1].startswith("No Page"):
                leaves[page] = leaf
    return leaves


def cmd_fetch(years: tuple[int, ...] = tuple(SESSIONS)) -> None:
    """Record UNT's two views of each page the days span, as raw sources:
    the words with their boxes and the OCR text page (both gzip, as UNT
    sends them); and the other copies' OCR text."""
    from tools.fetch import add_source
    have = {e["id"] for e in load_manifest()}
    for year in years:
        session = SESSIONS[year]
        leaves: dict[str, dict[int, int]] = {}
        license = UNT_LICENSE.format(year=year)
        for page in pages_needed(year):
            if words_id(page, year) in have and text_id(page, year) in have:
                continue
            record = unt_record(page, year)
            if record not in leaves:
                leaves[record] = unt_leaves(record)
            leaf = leaves[record].get(page)
            _expect(leaf is not None, f"{year}, p. {page}: no leaf in {record}")
            notes = (f"The Congressional Globe, {session.congress}, p. {page} "
                     f"(UNT Digital Library {record}, page {leaf}): ")
            if words_id(page, year) not in have:
                add_source(words_id(page, year), UNT_URL.format(record=record, leaf=leaf, what="annotations/ocr"),
                           license, notes + "the OCR's words and their boxes (IIIF annotations).", ext=".json.gz",
                           encoding="gzip")
            if text_id(page, year) not in have:
                add_source(text_id(page, year), UNT_URL.format(record=record, leaf=leaf, what="ocr"), license,
                           notes + "the OCR text page.", ext=".html.gz", encoding="gzip")
            print(f"{year} p. {page}", flush=True)
        for c in copies_used(session):
            if c.source_id in have:
                continue
            add_source(c.source_id, IA_URL.format(item=c.item), IA_LICENSE.format(year=year),
                       f"The Congressional Globe, {session.congress}, pp. {c.first}-{c.last} as UNT's records "
                       f"divide them. Internet Archive item {c.item} ({c.about}): OCR text, used for consensus.",
                       ext=".txt")
            print(f"{c.source_id}", flush=True)


if __name__ == "__main__":
    import sys
    args = sys.argv[1:]
    years = tuple(int(a) for a in args[1:]) if args[:1] == ["fetch"] else tuple(int(a) for a in args)
    if args[:1] == ["fetch"]:
        cmd_fetch(years or tuple(SESSIONS))
    else:
        for path in run(years=years or tuple(SESSIONS)):
            print(f"wrote {path}")
