"""The debates in Congress on the Thirteenth, Fourteenth and Fifteenth
Amendments, from the Congressional Globe (decisions 47 and 57).

The Congressional Globe prints three columns to a page under a running head
(the page number, "THE CONGRESSIONAL GLOBE." and the date). Each house's
proceedings for a day open with its name ("IN SENATE.", "HOUSE OF
REPRESENTATIVES.") and the date, and run as items under headings in small
capitals. In 1864 and 1865 the first page of each number of the Globe (one
page in sixteen) carries the number's masthead in place of the running head.

What is imported is fixed by the print: every item of either house's
proceedings on the days listed in `DAYS`, headed with the subject of the
joint resolution proposing the amendment (`Session.headings`: "Reconstruction"
in 1866; "Amendment of the Constitution", "Abolition of Slavery" in 1864-65;
"Suffrage", "Suffrage Constitutional Amendment", "Rights of Citizens" in
1869), whose first paragraphs name the joint resolution (`Session.subject`),
and the few places listed in `OPENINGS` where a house took the joint
resolution up without such a heading; each from its heading to the next
heading or the end of that house's day. An item headed "… again" goes on
with the item before it. Each item is a division (`House1866.May8`, a second
item that day `House1866.May8b`; `docs/references.md`).

Layout and words come from the University of North Texas Digital Library's
OCR of its copy (`unt-globe-{year}-p{page}-words`: each word and its box, no
punctuation; `-text`: the same OCR as lines of text, with punctuation),
split into columns (`importers/columns.py`). They are checked against the
Internet Archive's scans of other copies (`Session.copies`;
`importers/ocr.py`): the Lincoln Financial Foundation Collection's (1864,
1865 and 1866), and microfilms (1866 from page 2881, a third reading there;
and 1869).
"""

