HOUSES = {"House": "houseofrepresentatives", "Senate": "insenate"}


# "Mr. STEVENS.", "Mr. RICE, of Massachusetts.", "The SPEAKER.", "The PRESIDENT pro tempore."
SPEAKER = re.compile(r"(?:Mr|The)\W{0,3}\s+[A-Z][A-Z]{2,}\b")  # also as OCR reads it ("Mr.^ HOWARD.")


def one_case(text: str) -> bool:
    """Small capitals as UNT's OCR reads them: in capitals ("RECONSTRUCTION."),
    or in lower case from the first letter ("reconstruction.")."""
    cased = [c for c in text if c.isalpha()]
    if not cased:
        return False
    return (sum(c.isupper() for c in cased) >= 0.75 * len(cased)
            or (cased[0].islower() and sum(c.islower() for c in cased) >= 0.85 * len(cased)))


def is_heading(b: Block) -> bool:
    """An item heading: a short line set as a heading, ending in a full stop,
    in small capitals, which the OCR reads in capitals ("RECONSTRUCTION.")
    or in lower case from the first letter ("reconstruction."). A centred
    sentence ("The motion was agreed to."), a line of verse ("Too feeble
    implements to bind.") or a title line of a bill printed in the debate
    ("Article—.", "Constitution of the United States.") begins with a
    capital and goes on in lower case."""
    t = b.text.strip()
    return b.kind == "text" and b.heading and 1 <= len(t.split()) <= 9 and t.endswith(".") and one_case(t)


def is_subject_heading(b: Block, names: tuple[str, ...]) -> bool:
    """A heading on the subject (`subject_of`), which OCR may end with a
    comma ("SUFFRAGE,", "SUFFRAGE—AGAIN,"), a speck ("ABOLITION OF SLAVERY.
    Vf") or nothing ("ABOLITION OF SLA VJ511Y"). (Other headings ending so
    are not taken for headings: in
    1866 "INTERNAL REVENUE BILL.", read "ixteitnal ileyence but.,", was not,
    and the paragraphs under it stay where they were imported; see
    `Session.refined`.)"""
    t = re.sub(r"(?<=[.,])\s*[^\sA-Za-z]{0,2}\S{0,2}$", "", b.text.strip())
    return (b.kind == "text" and b.heading and 1 <= len(t.split()) <= 9 and one_case(t)
            and subject_of(Block(t, b.leaves, b.folios), names, strict=True) is not None)


def house_of(b: Block) -> str | None:
    """The house whose proceedings a block opens ("IN SENATE.", "HOUSE OF
    REPRESENTATIVES.", as OCR reads them), if it is such a heading."""
    t = letters(b.text)
    for house, name in HOUSES.items():
        if (b.kind == "text" and len(t) < len(name) + 30
                and SequenceMatcher(None, t[:len(name)], name).ratio() >= 0.8):
            return house
    return None


def subject_of(heading: Block, names: tuple[str, ...] = ("reconstruction",), strict: bool = False) -> str | None:
    """Which of the subject headings `names` a heading is, alone or with
    "again", as OCR reads it ("JtEOONSTJIUCTION.", "reconttiuotion.",
    "ABOLITION OF SLA.VJ511Y."): its name, or None."""
    t = letters(heading.text)
    for s in names:
        # (Strict: a long name may be misread more, "AUOMTION OF BUAVL3UY.",
        # but a short one must be closer: "RIGHTS OF WOMEN." is not "Rights
        # of Citizens".)
        # A short name ("SUITKAGE." for "SUFFRAGE.") must be of its length.
        floor = (0.6 if len(s) >= 18 or len(s) < 10 else 0.75) if strict else 0.65
        slack = 1 if strict and len(s) < 10 else 4
        # (Strict: "… again" only when the heading ends so; "CLAIMS OF LOYAL
        # CITIZENS." is not "Rights of Citizens again".)
        variants = (s, s + "again") if not strict or SequenceMatcher(None, t[-5:], "again").ratio() >= 0.6 else (s,)
        if any(SequenceMatcher(None, t, v).ratio() >= floor and abs(len(t) - len(v)) <= slack for v in variants):
            return s
    return None


def is_subject(heading: Block, names: tuple[str, ...] = ("reconstruction",), strict: bool = False) -> bool:
    return subject_of(heading, names, strict) is not None


def is_again(heading: Block, name: str) -> bool:
    """A heading "… again" ("Reconstruction again", "SUFFRAGE—AGAIN,")."""
    t = letters(heading.text)
    return "again" in t[len(name) - 2:] or (len(t) > len(name) + 2
                                            and SequenceMatcher(None, t, name + "again").ratio() >= 0.85)


@dataclass
class Item:
    house: str
    date: dt.date
    heading: Block | None  # None: printed inside an item on other business (`OPENINGS`)
    body: list[Block]
    again: bool = False


@lru_cache(maxsize=None)
def span_blocks(first: int, last: int, year: int = 1866) -> tuple[Block, ...]:
    cols = []
    for p in range(first, last + 1):
        cs = column_pages(unt_page(p, year), p, refined=SESSIONS[year].refined)
        _expect(cs is not None, f"{year}, p. {p}: not read as three columns")
        cols.extend(cs)
    bs = blocks(cols)
    if not SESSIONS[year].refined:
        return tuple(bs)
    # A paragraph set as a heading (taller type at the head of a column) that
    # begins in lower case after a paragraph that stops mid-sentence goes on
    # with it ("… Or, to be / explicit, were there no slavery all difficulty
    # would vanish."), or that has a quotation mark in it ("… the word" /
    # race," has been stricken out.").
    out: list[Block] = []
    for b in bs:
        prev = out[-1] if out else None
        if (prev is not None and b.heading and b.kind == prev.kind == "text" and re.match(r"[a-z]", b.text)
                and subject_of(b, SESSIONS[year].headings, True) is None
                and (not re.search(r"[.?!:;][\"'”’)\]]*$", re.sub(r"[/|\\^*•\s]+$", "", prev.text)) or '"' in b.text)):
            prev.text = join_across(prev.text, b.text)
            for leaf, folio in zip(b.leaves, b.folios):
                if leaf not in prev.leaves:
                    prev.leaves.append(leaf)
                    prev.folios.append(folio)
            continue
        out.append(b)
    return tuple(out)


def day_items(house: str, date: dt.date, first: int, last: int) -> list[Item]:
    """The imported items of one house's proceedings on one day."""
    session = SESSIONS[date.year]
    bs = list(span_blocks(first, last, date.year))
    start = next((k for k, b in enumerate(bs) if house_of(b) == house), None)
    _expect(start is not None, f"{house} {date}: the house's heading is not on pp. {first}–{last}")
    _expect(bs[start].folios[0] == str(first), f"{house} {date}: the house's heading is on p. {bs[start].folios[0]}")
    dateline = " ".join(b.text for b in bs[start:start + 2])
    # The weekday must be the date's ("Wednesday, Man 0> 1806." is May 9).
    m = re.search(r"([A-Za-z]+day)\W+([A-Za-z]{3,4})", dateline, re.I)
    ok = (m is not None and _weekday_ok(m.group(1), date)
          and max(SequenceMatcher(None, m.group(2).lower(), month).ratio()  # "Jlpril" is April
                  for month in (date.strftime("%B").lower(), date.strftime("%B").lower()[:len(m.group(2))])) >= 0.5)
    if not ok and session.refined:
        # (Refined: the weekday may be misread past recognizing, "Moxiuy,
        # February 15", "fti ESB AY February'?*, 1869.": the month. The page
        # is checked already.)
        words = re.findall(r"[A-Za-z]+|\d+", dateline)
        ok = any(SequenceMatcher(None, w.lower(), date.strftime("%B").lower()).ratio() >= 0.6 for w in words)
    _expect(ok, f"{house} {date}: the day's heading reads {dateline[:60]!r}")
    opening_heading, opening_para = OPENINGS.get((house, date), (None, None))
    misread = MISREAD_HEADINGS.get((house, date), {})
    used: set[str] = set()
    speech = set(SPEECH_HEADINGS.get((house, date), ()))
    found: set[str] = set()
    out: list[Item] = []
    current: Item | None = None
    ended = False
    for k in range(start + 1, len(bs)):
        b = bs[k]
        # (Refined: only with a date after it; "House of Representatives,"
        # also closes a letter printed in the debate.)
        if house_of(b) and (not session.refined
                            or (k + 1 < len(bs) and re.match(r"\W*[A-Za-z]+day\b", bs[k + 1].text))):
            ended = True
            break  # the other house, or the next day
        nxt = bs[k + 1] if k + 1 < len(bs) else None
        if ((is_heading(b) or (session.refined and is_subject_heading(b, session.headings))
                or (b.heading and letters(b.text) in misread)
                # (Refined: a heading OCR read without its full stop, "ML SSACK
                # I llOW THI! NHVVl H", before an item's opening.)
                or (session.refined and b.heading and b.kind == "text" and 1 <= len(b.text.split()) <= 9
                    and one_case(b.text) and nxt is not None and bool(ITEM_START.match(nxt.text))))
                and not (session.refined and not_heading(b, nxt))):
            inner = next((h for h in speech if SequenceMatcher(None, letters(b.text), h).ratio() >= 0.8), None)
            if current is not None and inner:
                found.add(inner)
                current.body.append(b)
                continue
            if (session.refined and current is not None and current.body and re.match(r"\W*[a-z]", b.text)
                    and subject_of(b, session.headings, session.refined) is None and letters(b.text) not in misread
                    and not (k + 1 < len(bs) and ITEM_START.match(bs[k + 1].text))):
                # A line in lower case set apart, not followed by the opening
                # of an item, ends a paragraph ("… where we get our \"vested
                # rights\" / to property.").
                prev = current.body[-1]
                current.body[-1] = Block(join_across(prev.text, b.text), prev.leaves + [l for l in b.leaves
                                         if l not in prev.leaves], prev.folios + [f for f in b.folios
                                         if f not in prev.folios], prev.kind, prev.first_indented, prev.heading)
                continue
            current = None
            name = subject_of(b, session.headings, session.refined)
            if letters(b.text) in misread:
                used.add(letters(b.text))
                current = Item(house, date, b, [], misread[letters(b.text)][1])
                out.append(current)
            elif name is not None:
                current = Item(house, date, b, [], is_again(b, name))
                out.append(current)
            elif opening_heading and SequenceMatcher(None, letters(b.text), opening_heading).ratio() >= 0.8:
                current = Item(house, date, b, [])
                out.append(current)
            continue
        if current is None and opening_para is not None and opening_para.search(b.text):
            current = Item(house, date, None, [])
            out.append(current)
            opening_para = None
        if current is not None:
            current.body.append(b)
    _expect(ended or current is None, f"{house} {date}: the last item runs past p. {last}")
    _expect(found == speech, f"{house} {date}: speech headings not found: {sorted(speech - found)}")
    _expect(used == set(misread), f"{house} {date}: misread headings not found: {sorted(set(misread) - used)}")
    # An item on the joint resolution names it in its first paragraphs; one
    # headed "… again" goes on with the one before it that day.
    kept = []
    for it in out:
        # (Refined: so does any later item headed with the subject that day,
        # as Morris's speech of May 31, 1864.)
        # (Refined: in its first ten paragraphs; on February 9, 1869, the
        # Senate argues over its business for seven before taking it up.)
        if it.body and (any(session.subject.search(b.text) for b in it.body[:10 if session.refined else 3])
                        or ((it.again or (session.refined and it.heading is not None
                                           and is_subject(it.heading, session.headings, True))) and kept)):
            kept.append(it)
    out = kept
    _expect(bool(out), f"{house} {date}: no item on the joint resolution")
    return out


# Lines set like a heading that are not item headings (refined reading):
# a speaker's words ("Mr. MORRILL. I do."), an article of a joint
# resolution ("ARTICLE XV."), and the signatures under a letter or a
# conference report ("W. M. STEWART.", "LEONARD MYERS." over "Managers on
# the part of the House.").
ARTICLE = re.compile(r"\W*A\w{5,7}\s+[XVIL1]+\W*$")
NAME = re.compile(r"\W*(?:[A-Za-z0-9'&]{1,3}\.?,?\s+|[A-Z][A-Z0-9'&]+,?\s+){1,3}[A-Z][A-Za-z0-9'&]+[.,]?\W*$")
INITIAL = re.compile(r"(?:^|\s)[A-Za-z0-9]{1,2}[.,](?:\s|$)")
SIGNATURE_NEXT = re.compile(r"\W*(?:Managers|President\s+of|Speaker\s+of|Secretary|Sergeant|By\s+the\s+Governor"
                            r"|In\s+charge|Hon\.|To\s+|[A-Z][A-Z0-9'.]+\s+[A-Z]{1,2}\.\s*[A-Z])")


def not_heading(b: Block, nxt: Block | None) -> bool:
    t = b.text.strip()
    if SPEAKER.match(t) or ARTICLE.match(t):
        return True
    opens_item = nxt is not None and bool(ITEM_START.match(nxt.text))
    return (bool(NAME.match(t)) and len(t.split()) <= 5 and not opens_item
            and (bool(INITIAL.search(t)) or (nxt is not None and bool(SIGNATURE_NEXT.match(nxt.text)))))


# How an item's first paragraph opens: a speaker ("Mr. ASHLEY.", "The
# SPEAKER."), a motion, a message, the business taken up.
ITEM_START = re.compile(r"\W*(?:(?:Mr|Mrs|Messrs|The)\W{0,3}\s+[A-Z][A-Z]{2,}|On\s+motion|A\s+message|Mr\.\s"
                        r"|The\s+(?:House|Senate|joint|bill|question|resolution|following|amendment|motion|morning"
                        r"|unfinished|special|Chair|Secretary|Clerk|Committee))")


def _weekday_ok(read: str, date: dt.date) -> bool:
    names = ("monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday")
    return SequenceMatcher(None, letters(read), names[date.weekday()]).ratio() >= 0.6


def all_items(year: int = 1866) -> list[Item]:
    return [it for house, date, first, last in days_of(year) for it in day_items(house, date, first, last)]


