def days_of(year: int) -> list[tuple[str, dt.date, int, int]]:
    return [d for d in DAYS if d[1].year == year]


def pages_needed(year: int = 1866) -> list[int]:
    return sorted({p for _, _, first, last in days_of(year) for p in range(first, last + 1)})


def words_id(page: int, year: int = 1866) -> str:
    return f"unt-globe-{year}-p{page}-words"


def text_id(page: int, year: int = 1866) -> str:
    return f"unt-globe-{year}-p{page}-text"


def unt_record(page: int, year: int = 1866) -> str:
    rec = next((r for r, first, last in SESSIONS[year].parts if first <= page <= last), None)
    _expect(rec is not None, f"{year}, p. {page}: in no UNT record")
    return rec


@lru_cache(maxsize=None)
def _urls() -> dict[str, str]:
    return {e["id"]: e["url"] for e in load_manifest()}


def unt_leaf(page: int, year: int = 1866) -> int:
    """The page's place in UNT's record (its page image is m1/{leaf}/), from
    the URL its words were fetched from."""
    m = re.search(r"/m1/(\d+)/", _urls()[words_id(page, year)])
    _expect(m is not None, f"p. {page}: no UNT page in {words_id(page, year)}")
    return int(m.group(1))


