def is_heading(b: Block, nxt: Block | None) -> bool:
    """An item heading: a line set as a heading, in capitals, before an
    item's opening (a speaker,
    a message, the business taken up). A heading followed by more of a
    speech is one of the sections a speech is printed in ("REVIEW OF INCOME
    TAX IN CONGRESS.", July 12, 1909), and stays in it (and see
    `SPEECH_HEADINGS`). The end of a paragraph set apart is no heading ("… from Alabama [Mr. /
    CLAYTON]."), nor are a speaker's words ("Mr. UNDERWOOD. I do.", however
    OCR reads "Mr.")."""
    t = b.text.strip()
    cased = [c for c in t if c.isalpha()]
    return (b.kind == "text" and b.heading and 1 <= len(t.split()) <= 16 and len(cased) >= 3
            and sum(c.isupper() for c in cased) >= 0.75 * len(cased)
            and not SPEAKER.match(t) and not re.match(r"\W*M\w{0,2}\W{0,3}\s", t)
            and not re.search(r"[A-Z0-9'’]{2,}\.\s+(?:\S+\s+)?\S*[a-z]", t)
            and not re.search(r"[\[\]]", t) and not t.endswith(":") and not re.match(r"\W*By\s", t)
            and not SIGNED.match(t) and not PLACE_DATE.search(t)
            and nxt is not None and opens_item(nxt))



def opens_item(b: Block) -> bool:
    """How an item's first paragraph opens (`globe.ITEM_START`), or a
    speaker's name in capitals after a short first word OCR may misread
    ("Tbe VICE-PRESIDENT.", "1\\Ir. BORAH."); not a speech going on ("Mr.
    Speaker, this brings me to …"), nor a letter's place and date ("IOLA,
    KANS., January 5, 1917.")."""
    cased = [c for c in b.text if c.isalpha()]
    capitals = (bool(cased) and sum(c.isupper() for c in cased) >= 0.75 * len(cased)  # another heading line
                and not b.text.rstrip().endswith(":"))
    return ((bool(ITEM_START.match(b.text)) or bool(re.match(r"\W*\S{1,6}\s+[A-Z][A-Z'’-]{2,}", b.text))
             or bool(re.match(r"\W*By\s+\S{1,6}(?:\s?\.)?\s+[A-Z]{3}", b.text))  # "By Mr. SMOOT:" (bills introduced)
             or bool(OPENING.match(b.text)) or bool(ROUTINE.match(b.text)))
            and not ADDRESS.match(b.text) and not capitals and not PLACE_DATE.search(b.text[:60])
            and not PLACE.match(b.text))


# The signature of a letter ("D. A. HOLLINGSWORTH.", "CHAS. E. TOWNSEND.") and the place and date
# it was written ("PORTLAND, OREG., July 30."), printed in the debate.
SIGNED = re.compile(r"^\W*(?:[A-Z][A-Za-z]{0,4}\s?\.\s*){1,3}[A-Z][A-Za-z'’-]+[.,]?\W*$")
# A letter's closing, before its signature ("Very truly, yours,").
# A letter's place ("TROY, KANS., Fe1JrtUJry 5, W11.").
PLACE = re.compile(r"^\W*[A-Z][\w.'’ -]{1,25},\s+[A-Z][A-Za-z]{1,6}\.?,\s")
CLOSING = re.compile(r"(?i)(?:yours|truly|respectfully|sincerely|remain|obedient\s+servant)\W*$")
PLACE_DATE = re.compile(r"(?i)\b(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\W{0,2}\s*\d|\b1[89]\d\d\W*$")

# The business taken up after a first word OCR garbled ("'l'he Sen:at-e, ;as
# in :Committee of the Whole").
OPENING = re.compile(r"\W*\S{1,4}\s+\W?(?:Sen\W?a|House|Chair|Secretary|Clerk|Committee|morning|unfinished)", re.I)
# The Record's routine items open with a formula ("Bills and joint resolutions
# were introduced, read the first time, …", "Under clause 2 of Rule XXIV, …").
ROUTINE = re.compile(r"\W*(?:Bills\s+(?:and\s+joint\s+resolutions\s+)?were|Under\s+clause|By\s+unanimous\s+consent"
                     r"|Petitions\s+and|Messages?\s+in\s+writing|Sundry\s+messages)", re.I)
ADDRESS = re.compile(r"\W*M\w{0,2}\W{0,3}\s*(?:Speaker|President|Chairman)\b")


def named_heading(b: Block, names: tuple[str, ...]) -> bool:
    return any(like(b.text, n) or like(b.text, n + "again") for n in names)


def like(text: str, name: str, floor: float = 0.75) -> bool:
    t = letters(text)
    return SequenceMatcher(None, t, name).ratio() >= floor and abs(len(t) - len(name)) <= max(2, len(name) // 5)


def house_of(b: Block) -> str | None:
    for house, name in HOUSES.items():
        if b.kind == "text" and len(letters(b.text)) <= len(name) + 2 and like(b.text, name):
            return house
    return None


def is_dateline(b: Block, date: dt.date | None) -> bool:
    """A day's dateline ("MONDAY, July 12, 1909."): of that date (its month,
    and its weekday or its day: "TrasnAY, May 16, 19 11."), or (None) of any.
    A line of more than eight words is not one."""
    words = [w.lower() for w in re.findall(r"[A-Za-z]+", b.text)]
    if date is None:
        return (len(words) <= 4 and bool(words)
                and max(SequenceMatcher(None, words[0], d).ratio() for d in WEEKDAYS) >= 0.7)
    if len(b.text.split()) > 8:
        return False
    if (any(SequenceMatcher(None, w, date.strftime("%B").lower()).ratio() >= 0.7 for w in words)
            and (any(SequenceMatcher(None, w, WEEKDAYS[date.weekday()]).ratio() >= 0.7 for w in words)
                 or bool(re.search(rf"\b{date.day}\b", b.text)))):
        return True
    # (Misread past that, "Fnmu, Ap1·il ~6, 1912.", "TUESDAY, Ap ' ril ~3, 191B .":
    # the letters, with the year ("191!") or the weekday, and the day's last figure.)
    days = re.findall(r"(?<![A-Za-z\d])\d{1,2}(?!\d)", b.text)
    return ((str(date.year)[:3] in b.text.replace(" ", "")
             or any(SequenceMatcher(None, w, WEEKDAYS[date.weekday()]).ratio() >= 0.7 for w in words))
            and any(d[-1] == str(date.day)[-1] for d in days)
            and SequenceMatcher(None, letters(b.text), WEEKDAYS[date.weekday()] + date.strftime("%B").lower()).ratio()
            >= 0.5)


def index_pages(spec: str) -> list[int]:
    out = []
    for part in spec.split(","):
        lo, _, hi = part.strip().partition("-")
        out.extend(range(int(lo), int(hi or lo) + 1))
    return out


def day_items(number: int, house: str, date: dt.date, granule: str, pages: str) -> list[Item]:
    """The imported items of one house's proceedings on one day."""
    session = session_of(granule)
    amendment = AMENDMENTS[number]
    bs = list(granule_blocks(granule, session.columns))
    start = next((k for k, b in enumerate(bs[:-1]) if house_of(b) == house and is_dateline(bs[k + 1], date)), None)
    if start is None:
        # (The house's name not read, July 31, 1917: the dateline alone.)
        start = next((k - 1 for k, b in enumerate(bs) if k and b.heading and is_dateline(b, date)), None)
    _expect(start is not None, f"{house} {date}: the house's heading and dateline are not in {granule}")
    names = amendment.headings + EXTRA_HEADINGS.get((house, date), ())
    inner = SPEECH_HEADINGS.get((house, date), ())
    found: set[str] = set()
    out: list[Item] = []
    current: Item | None = None
    inside = list(INSIDE.get((house, date), []))
    within: re.Pattern | None = None  # the end of an item inside another
    ended = False
    for k in range(start + 2, len(bs)):
        b = bs[k]
        if within is not None:
            current.body.append(b)
            if within.search(b.text):
                current, within = None, None
            continue
        if current is None and inside and inside[0][0].search(b.text):
            current, within = Item(house, date, granule, None, [b]), inside.pop(0)[1]
            out.append(current)
            continue  # (with no end given, to the next heading)
        if house_of(b) and k + 1 < len(bs) and is_dateline(bs[k + 1], None):
            ended = True
            break  # the other house, or the next day
        # (A heading after the source of a document printed in the debate,
        # "[The Atlanta Georgian.]", is the document's.)
        # (So is one after a letter's closing, its signature; one after a
        # paragraph ending in a colon, which introduces a quotation; or one
        # before a letter's place and date, "ALLEN COUNTY." over "IOLA, KANS.,
        # January 5, 1917.", July 31, 1917.)
        # (Nor is the end of a paragraph that stops on "from" or "the": "… the
        # gentleman from / [Mr. MONDELL].", May 21, 1919.)
        if re.search(r"\b(?:from|the|of|to|and|by|for|with|in)\s*$", bs[k - 1].text) and not named_heading(b, names):
            if current is not None:
                current.body.append(b)
            continue
        document = current is not None and (bool(re.match(r"\s*\[[^\]]*\]\W*$", bs[k - 1].text))
                                            or bool(CLOSING.search(bs[k - 1].text[-40:]))
                                            or bs[k - 1].text.rstrip().endswith(":")
                                            or (k + 1 < len(bs) and (bool(PLACE_DATE.search(bs[k + 1].text[:60]))
                                                                      or bool(PLACE.match(bs[k + 1].text)))))
        # (A heading of the subject, or one listed for the day, is an item's
        # heading even before an opening OCR garbled past recognizing.)
        named = (b.kind == "text" and b.heading and not document and len(b.text.split()) <= 16
                 and any(like(b.text, n) or like(b.text, n + "again") for n in names))
        if (named or is_heading(b, bs[k + 1] if k + 1 < len(bs) else None)) and not INNER.match(b.text) and not document:
            if current is not None and named and not is_heading(b, bs[k + 1] if k + 1 < len(bs) else None):
                # (The title of a document printed in the item, which repeats
                # the subject: "NATIONAL CONTROL OVER ELECTION OF SENATORS.",
                # over the minority's views, May 22, 1911.)
                current.body.append(b)
                continue
            if current is not None and any(like(b.text, h) for h in inner):
                found.update(h for h in inner if like(b.text, h))
                current.body.append(b)
                continue
            current = None
            if named:
                current = Item(house, date, granule, b, [])
                out.append(current)
            continue
        if current is not None:
            current.body.append(b)
    _expect(ended or current is None, f"{house} {date}: the last item runs past the end of {granule}")
    _expect(found == set(inner), f"{house} {date}: speech headings not found: {sorted(set(inner) - found)}")
    _expect(within is None and not inside, f"{house} {date}: an item inside another is not found or not ended")
    # An item on the joint resolution names it in its heading or first paragraphs.
    # (Not one under a heading listed for the day, read off the page.)
    extra = EXTRA_HEADINGS.get((house, date), ())
    out = [it for it in out if any(amendment.subject.search(b.text) for b in [*([it.heading] if it.heading else []),
                                                                                 *it.body[:10]])
           or (it.heading is not None and any(like(it.heading.text, n) for n in extra))]
    _expect(bool(out), f"{house} {date}: no item on the joint resolution")
    # Every page the index gives for the day is in an item imported.
    spans = [(int((it.heading or it.body[0]).folios[0]), max(int(f) for b in it.body or [it.heading] for f in b.folios))
             for it in out]
    listed = index_pages(pages) + [p for p in ELSEWHERE.get((house, date), {})]
    missing = [p for p in index_pages(pages) if not any(lo <= p <= hi for lo, hi in spans)
               and p not in ELSEWHERE.get((house, date), {})]
    # And no item runs on far past the pages the index gives (a heading not
    # read as one).
    last = RUNS_TO.get((house, date), max(listed) + 1)
    _expect(all(hi <= last for _, hi in spans), f"{house} {date}: an item runs past p. {last}: {spans}")
    _expect(not missing, f"{house} {date}: the index's pages {missing} are in no item imported "
                         f"(items: {spans}; headings: {[it.heading and it.heading.text for it in out]})")
    return out

