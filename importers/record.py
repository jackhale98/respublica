"""The debates in Congress on the Sixteenth to Twenty-sixth Amendments, from
the bound Congressional Record (decision 61).

govinfo.gov (the Government Publishing Office) serves the bound edition as
scans with an OCR text layer, one PDF per house per day (a "granule"); the
granule PDFs are raw sources, as is each part's MODS record, which gives
each granule's printed pages. Pages are read from the text layer
(`tools.pdf.pdf_words`), split into columns and paragraphs as the
Congressional Globe's are (`importers.globe`, `importers.columns`), and
checked word by word against the Internet Archive's OCR of a microfilm of
the same bound part (`importers.ocr`), whose page images the errata page
shows.

What is imported is fixed by the print and the Record's own index: on each
day the volume's History of Bills and Resolutions lists for the joint
resolution (`DAYS`, with the pages it gives), every item of that house's
proceedings headed with the resolution's subject (`Amendment.headings`, and
for a day `EXTRA_HEADINGS` where the house took it up under another
heading), from its heading to the next heading or the end of the house's
day, provided its first paragraphs name the joint resolution
(`Amendment.subject`). Every page the index gives must fall in an item
imported (`day_items`). Speeches printed in the Appendix by leave are not
imported. Each item is a division (`House1909.Jul12`, a second item that
day `House1909.Jul12b`; `docs/references.md`).
"""

