@dataclass(frozen=True)
class Session:
    """A session of Congress and its bound volume: its parts' Internet
    Archive microfilm items (by govinfo package), and the edition."""
    key: str  # "1909": the year, with a letter for a second session in the same year
    congress: str  # "61st Congress, 1st session"
    volume: int
    year: int  # the volume's year, as govinfo names its packages
    columns: int
    microfilm: tuple[tuple[str, str], ...]  # (govinfo package, Internet Archive item)
    # The later volumes (1932 on): headings without a full stop, the running
    # head nearer the text. Rules for them apply only here, so the earlier
    # works' text (and refs) stay as they are.
    later: bool = False

    @property
    def edition(self) -> str:
        return (f"Congressional Record: Containing the Proceedings and Debates of the {self.congress}, "
                f"vol. {self.volume} (Washington: Government Printing Office, {self.year}), the bound edition")


