@lru_cache(maxsize=None)
def microfilm(package: str) -> dict[int, tuple[int, str]]:
    """The Internet Archive's microfilm of a part: for each printed page, its
    leaf (counting from 1, as `scan.leaves` do) and its OCR text. A page
    number the Internet Archive read counts when it fits the pages around it
    (`globe.settle_pages`); the others take theirs from their neighbours."""
    from importers.globe import settle_pages
    numbers = json.loads(raw_path(ia_id(package, "pages")).read_text(encoding="utf-8"))["pages"]
    index = json.loads(gzip.decompress(raw_path(ia_id(package, "pageindex")).read_bytes()))
    text = gzip.decompress(raw_path(ia_id(package, "text")).read_bytes()).decode("utf-8")
    _expect(len(numbers) == len(index), f"{package}: the microfilm's page numbers and text disagree in length")
    read = {p["leafNum"]: int(p["pageNumber"]) if str(p.get("pageNumber") or "").isdigit() else None
            for p in numbers}
    out: dict[int, tuple[int, str]] = {}
    for leaf, n in sorted(settle_pages(read).items()):
        if n not in out:
            start, end = index[leaf][0], index[leaf][1]
            out[n] = (leaf + 1, text[start:end])
    return out


def reference(granule: str) -> Reference:
    """The microfilm's OCR of the granule's pages, in page order."""
    first, last = printed_range(granule)
    pages = microfilm(package_of(granule))
    missing = [p for p in range(first, last + 1) if p not in pages]
    _expect(len(missing) <= (last - first + 1) // 4, f"{granule}: the microfilm lacks pp. {missing}")
    return Reference("microfilm", "\n".join(pages[p][1] for p in range(first, last + 1) if p in pages))


CHUNK = 200


def prepare(its: list[Item]) -> dict[int, list[dict]]:
    """Each block's words aligned with the microfilm's, in runs of paragraphs
    of at least CHUNK words (as `globe.prepare` does for its refined years)."""
    readings: dict[int, list[dict]] = {}
    refs: dict[str, Reference] = {}
    hints: dict[str, int] = {}
    for it in its:
        if it.granule not in refs:
            refs[it.granule] = reference(it.granule)
            hints = {}
        ref = [refs[it.granule]]
        stream = [*([it.heading] if it.heading else []), *(b for b in it.body if b.kind != "note")]
        chunks: list[list[Block]] = [[]]
        for b in stream:
            if sum(len(TOKEN.findall(x.text)) for x in chunks[-1]) >= CHUNK:
                chunks.append([])
            chunks[-1].append(b)
        for chunk in chunks:
            tokens = [TOKEN.findall(b.text) for b in chunk]
            aligned = align([t for ts in tokens for t in ts], ref, hints)
            at = 0
            for b, ts in zip(chunk, tokens):
                readings[id(b)] = aligned[at:at + len(ts)]
                at += len(ts)
        for b in it.body:
            if b.kind == "note":
                readings[id(b)] = align(TOKEN.findall(b.text), ref, dict(hints))
    return readings


