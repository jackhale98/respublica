ORDINALS = {16: "Sixteenth", 17: "Seventeenth", 18: "Eighteenth", 19: "Nineteenth", 20: "Twentieth",
            21: "Twenty-first", 22: "Twenty-second", 23: "Twenty-third", 24: "Twenty-fourth", 25: "Twenty-fifth",
            26: "Twenty-sixth"}
HOUSE_NAMES = {"Senate": "the Senate", "House": "the House of Representatives"}


def work_of(house: str, session: Session, amendment: Amendment) -> dict:
    """A work's id, ref prefix, title and short title: one per house per
    session ("Senate1909"; a second session in one year takes a letter,
    "Senate1917b")."""
    year = session.key.rstrip("b")
    when = year if not session.key.endswith("b") else f"{year} ({session.congress.split(', ')[1]})"
    return {"id": f"{house.lower()}-{ORDINALS[amendment.number].lower()}-amendment-{session.key}",
            "prefix": f"{house}{session.key}",
            "title": f"Debates in {HOUSE_NAMES[house]} on the {ORDINALS[amendment.number]} Amendment, {when}",
            "short": f"{house} debates, {when}"}


def scan_of(b: Block, granule: str) -> dict:
    """Where a paragraph is in the scans: the granule's pages (govinfo), and
    the microfilm's leaves for the same printed pages (their images)."""
    pages = microfilm(package_of(granule))
    first, _ = printed_range(granule)
    _expect(all(first + leaf - 1 in pages for leaf in b.leaves),
            f"{granule}: the microfilm has no page for a paragraph on pp. {b.folios}")
    return {"item": granule, "leaves": list(b.leaves), "site": "govinfo",
            "microfilm": {"item": dict(session_of(granule).microfilm)[package_of(granule)],
                          "leaves": [pages[first + leaf - 1][0] for leaf in b.leaves]}}


def build(house: str, session: Session, amendment: Amendment, its: list[Item], readings: dict[int, list[dict]],
          known: set[str]) -> dict:
    work = work_of(house, session, amendment)
    prefix = work["prefix"]
    divisions, segments = [], []
    seen: dict[str, int] = {}
    for it in its:
        day = f"{it.date.strftime('%b')}{it.date.day}"
        seen[day] = seen.get(day, 0) + 1
        suffix = "" if seen[day] == 1 else "bcdefghij"[seen[day] - 2]
        base = f"{prefix}.{day}{suffix}"
        label = f"{it.date.strftime('%B')} {it.date.day}, {it.date.year}" + (f" ({seen[day]})" if suffix else "")
        div = {"date": it.date.isoformat(), "label": label, "level": 1, "ref": base}
        if it.heading is not None:
            head, spans = text_of_readings(readings[id(it.heading)], known)
            div["title"] = head
            if spans:
                div["uncertain"] = {"title": spans}
        divisions.append(div)
        body = [b for b in it.body if b.kind != "note"]
        notes = [b for b in it.body if b.kind == "note"]
        for kind, bs, ref_of, label_of in (
                (None, body, lambda n: f"{base}.{n}", lambda n: f"{house}, {label}, ¶ {n}"),
                ("footnote", notes, lambda n: f"{base}.fn{n}", lambda n: f"{house}, {label}, note {n}")):
            for n, b in enumerate(bs, 1):
                text, spans, fixed = corrections.apply(ref_of(n), *text_of_readings(readings[id(b)], known))
                seg = {"label": label_of(n), "pages": b.folios, "ref": ref_of(n), "scan": scan_of(b, it.granule),
                       "text": text}
                if kind:
                    seg["kind"] = kind
                if spans:
                    seg["uncertain"] = spans
                if fixed:
                    seg["corrected"] = fixed
                segments.append(seg)
    pages = sorted({int(f) for s in segments for f in s["pages"]})
    granules = list(dict.fromkeys(it.granule for it in its))
    packages = list(dict.fromkeys(package_of(g) for g in granules))
    days = sorted({it.date for it in its})
    return {
        "date": f"{days[0].isoformat()}/{days[-1].isoformat()}",
        "divisions": divisions,
        "edition": {"name": session.edition,
                    "notes": f"{session.edition}: the items of the proceedings of {HOUSE_NAMES[house]} headed with "
                             f"the subject in which it took up the joint resolution ({amendment.resolution}) "
                             f"proposing the {ORDINALS[amendment.number]} Amendment, on the days the volume's "
                             f"History of Bills and Resolutions lists for it, pp. {pages[0]}–{pages[-1]}; not the "
                             "speeches printed in the Appendix. Read from the text layer of the Government "
                             "Publishing Office's scans (govinfo.gov) and checked word by word against the "
                             "Internet Archive's OCR of a microfilm of the same part; words they could not settle "
                             "are marked as uncertain. See docs/editions.md."},
        "id": work["id"],
        "ref_prefix": prefix,
        "segments": segments,
        "short": work["short"],
        "source_ids": [granule_id(g) for g in granules] + [mods_id(p) for p in packages]
                      + [ia_id(p, what) for p in packages for what in IA_FILES],
        "title": work["title"],
    }


def run(out_dir: Path = TEXTS_DIR) -> list[Path]:
    # (The words the scans attest are counted apart for the volumes of 1909-19
    # and those from 1932, so that adding the one does not change the other.)
    clean = clean_vocabulary()
    known = {False: Vocabulary(clean), True: Vocabulary(clean)}
    groups: dict[tuple[int, str, str], list[Item]] = {}
    for number, house, date, granule, pages in DAYS:
        groups.setdefault((number, house, session_of(granule).key), []).extend(
            day_items(number, house, date, granule, pages))
    readings: dict[int, list[dict]] = {}
    for (_, _, key), its in groups.items():
        rs = prepare(its)
        readings.update(rs)
        for r in rs.values():
            known[SESSIONS[key].later].attest(attested(r))
    paths = []
    for (number, house, key), its in groups.items():
        work = build(house, SESSIONS[key], AMENDMENTS[number], its, readings, known[SESSIONS[key].later])
        path = out_dir / f"{work['id']}.json"
        write_json(path, work)
        paths.append(path)
    return paths


