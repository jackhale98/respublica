@lru_cache(maxsize=None)
def printed_range(granule: str) -> tuple[int, int]:
    """A granule's first and last printed pages, from its part's MODS record."""
    t = raw_path(mods_id(package_of(granule))).read_text(encoding="utf-8")
    m = re.search(rf'ID="id-{re.escape(granule)}".*?<printPageRange first="(\d+)" last="(\d+)"', t, re.S)
    _expect(m is not None, f"{granule}: no printed pages in its part's MODS record")
    return int(m.group(1)), int(m.group(2))


def to_page(leaf: int, width: float, height: float, words: list) -> Page:
    """A page of the text layer as `importers.ocr` reads a scan: words in
    pixels at 300 dpi, put into lines by their baselines. A gap wider than
    one and a half times the type size (the gutter) ends a line, so that two
    columns' lines at one height stay apart."""
    ws = sorted(words, key=lambda w: (round(w.y), w.x))
    lines: list[list] = []
    for w in ws:
        last = lines[-1][-1] if lines else None
        if (last is not None and abs(last.y - w.y) <= max(1.0, 0.3 * w.size) and w.x >= last.x
                and w.x - last.x1 < 1.5 * w.size):
            lines[-1].append(w)
        else:
            lines.append([w])
    # The signature mark at the foot of the first page of each sheet (the
    # volume and the sheet: "XLIV—277") is not text.
    lines = [ln for ln in lines if not (SIGNATURE.match(" ".join(w.text for w in ln)) and ln[0].y > 0.9 * height)]
    # The running head (the page number, "CONGRESSIONAL RECORD—SENATE." and
    # the date) is the top row, standing well apart from the text below it.
    # (Specks, which OCR reads as stops and dots, are not print.)
    printed = [ln for ln in lines if len(re.sub(r"\W", "", "".join(w.text for w in ln))) >= 2]
    if printed:
        top = min(ln[0].y for ln in printed)
        head = max(w.size for ln in printed if ln[0].y <= top + 2 for w in ln)
        body = sorted(ln[0].y for ln in printed if ln[0].y > top + 0.5 * head)
        size = sorted(w.size for ln in printed for w in ln)[sum(len(ln) for ln in printed) // 2]
        if top < 0.15 * height and body and body[0] - top > 2.2 * size:
            lines = [ln for ln in lines if ln[0].y > top + 0.5 * head]
    page = Page(leaf, int(width * SCALE), int(height * SCALE))
    for ln in lines:
        page.paras.append(Para([Line([Word(w.text, round(w.x * SCALE), round((w.y - 0.75 * w.size) * SCALE),
                                           round(w.x1 * SCALE), round((w.y + 0.2 * w.size) * SCALE), 0)
                                      for w in ln])], leaf))
    return page


SIGNATURE = re.compile(r"^\W*[XLVIC1l]{2,7}\W{1,4}\d{1,4}\W*$")


@lru_cache(maxsize=None)
def granule_words(granule: str) -> tuple:
    return tuple(pdf_words(raw_path(granule_id(granule))))


def granule_pages(granule: str) -> tuple[Page, ...]:
    return tuple(to_page(k, p.width, p.height, p.words) for k, p in enumerate(granule_words(granule), 1))


def granule_heads(granule: str) -> tuple[str, ...]:
    """The words near the top of each page (the running head)."""
    return tuple(" ".join(w.text for w in p.words if w.y < 0.1 * p.height) for p in granule_words(granule))


@lru_cache(maxsize=None)
def granule_blocks(granule: str, columns: int) -> tuple[Block, ...]:
    """The granule's paragraphs, in reading order, numbered by printed page.
    Its pages follow the printed pages in order; the running head of most
    pages must give the page's number."""
    first, last = printed_range(granule)
    pages = granule_pages(granule)
    heads = granule_heads(granule)
    _expect(len(pages) == last - first + 1, f"{granule}: {len(pages)} pages for pp. {first}-{last}")
    cols, read = [], 0
    for page in pages:
        number = first + page.leaf - 1
        head = heads[page.leaf - 1]
        # (OCR misreads the first figures of a page number: "~102", "11105".)
        read += any(n.endswith(str(number)[-2:]) for n in re.findall(r"\d{2,}", head.replace(" ", "")))
        cs = split_columns(page, set(), columns)
        if cs is None and page.paras:
            # A page printed in one column only (the last of a part).
            left, right = body_span(page)
            if right - left < 0.6 * page.width:
                cs = split_columns(page, set(), 1)
        _expect(cs is not None, f"{granule}, p. {number}: not read as {columns} columns")
        for col in cs:
            col.paras = paragraphs(col, refined=True)
            mark_notes(col)
            col.folio = col.number = str(number)
        cols.extend(cs)
    _expect(read >= 0.5 * len(pages), f"{granule}: only {read} of {len(pages)} running heads give the page")
    return tuple(rejoin(blocks(cols)))


