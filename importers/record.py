def package_of(granule: str) -> str:
    return re.sub(r"-\d+-\d+$", "", granule)


def granule_id(granule: str) -> str:
    """The raw source id of a granule's PDF."""
    return "govinfo-" + granule.lower().removeprefix("gpo-")


def mods_id(package: str) -> str:
    return "govinfo-" + package.lower().removeprefix("gpo-") + "-mods"


def ia_id(package: str, what: str) -> str:
    return "ia-record-" + package.lower().removeprefix("gpo-crecb-") + "-" + what


def session_of(granule: str) -> Session:
    package = package_of(granule)
    s = next((s for s in SESSIONS.values() if any(p == package for p, _ in s.microfilm)), None)
    _expect(s is not None, f"{granule}: in no session's parts")
    return s


