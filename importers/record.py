def cmd_fetch() -> None:
    """Record each day's granule PDF, its part's MODS record, and the
    Internet Archive's OCR text and page numbers of the microfilmed part."""
    from tools.fetch import add_source
    have = {e["id"] for e in load_manifest()}
    for _, house, date, granule, _ in DAYS:
        session = session_of(granule)
        package = package_of(granule)
        if mods_id(package) not in have:
            add_source(mods_id(package), MODS_URL.format(package=package), GOVINFO_LICENSE,
                       f"Congressional Record (bound edition), vol. {session.volume}, govinfo package {package}: "
                       "its MODS record, which gives each granule's printed pages.", ext=".xml")
            have.add(mods_id(package))
            print(mods_id(package), flush=True)
        if granule_id(granule) not in have:
            add_source(granule_id(granule), GRANULE_URL.format(package=package, granule=granule), GOVINFO_LICENSE,
                       f"Congressional Record (bound edition), vol. {session.volume}, {house}, "
                       f"{date:%B} {date.day}, {date.year} (govinfo granule {granule}): scan with its OCR text "
                       "layer.", ext=".pdf")
            have.add(granule_id(granule))
            print(granule_id(granule), flush=True)
        item = dict(session.microfilm)[package]
        for what, (suffix, ext) in IA_FILES.items():
            sid = ia_id(package, what)
            if sid in have:
                continue
            add_source(sid, IA_URL.format(item=item, suffix=suffix), IA_LICENSE.format(year=session.year),
                       f"Congressional Record (bound edition), vol. {session.volume}, the part govinfo calls "
                       f"{package}: Internet Archive item {item} (microfilm), {what}; used for consensus and "
                       "its page images.", ext=ext)
            have.add(sid)
            print(sid, flush=True)


